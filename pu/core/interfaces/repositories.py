"""Persistence contracts used by application/domain code.

SQLite is the local adapter. Operational state depends on repository contracts
so another database can replace workflow/event/audit/approval storage without
changing agents or harnesses.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class MemoryRepository(Protocol):
    def gated_retrieve(self, message: str, notify=None) -> str: ...
    def matching_skills(self, message: str) -> str: ...
    def log_chat(
        self,
        user_message: str,
        reply: str,
        session_id: str = "default",
        source: str = "cli",
        meta: dict | None = None,
    ) -> None: ...
    def session_history(self, session_id: str) -> list[tuple[str, str]]: ...
    def list_sessions(self) -> list[dict]: ...
    def export_markdown(self) -> None: ...
    def maybe_consolidate(self, notify=None) -> None: ...


@runtime_checkable
class ConnectionFactory(Protocol):
    def __call__(self, home: Path, check_same_thread: bool = True) -> Any: ...


@runtime_checkable
class WorkflowRepository(Protocol):
    def create(self, workflow_id: str, request: Any) -> Any: ...
    def get(self, workflow_id: str) -> Any | None: ...
    def request(self, workflow_id: str) -> Any: ...
    def start_attempt(self, workflow_id: str) -> Any: ...
    def set_current_stage(self, workflow_id: str, stage_name: str) -> None: ...
    def save_checkpoint(self, workflow_id: str, stage_name: str, result: Any) -> None: ...
    def checkpoint_failure(self, workflow_id: str, stage_name: str, error: str) -> None: ...
    def checkpoints(self, workflow_id: str) -> dict[str, Any]: ...
    def mark_failed(self, workflow_id: str, error: str) -> Any: ...
    def mark_completed(self, workflow_id: str, *, report_id: str | None = None) -> Any: ...
