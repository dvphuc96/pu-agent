"""Vendor-free Human Approval contracts."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Protocol, runtime_checkable

from pu.core.interfaces.tools import ToolContext, ToolDefinition, ToolResult

if TYPE_CHECKING:
    # Annotation-only. Importing the implementation package at runtime would
    # recreate the registry -> interfaces -> approval -> harness -> registry
    # cycle that broke `pu connect gmail` (pu.tools imported before pu.harness).
    from pu.approval.models import ApprovalStatus, ProposedAction


@runtime_checkable
class ApprovalRepository(Protocol):
    def create(self, action: ProposedAction) -> ProposedAction: ...
    def get(self, action_id: str) -> ProposedAction | None: ...
    def list(self, *, limit: int = 100, status: ApprovalStatus | None = None) -> list[ProposedAction]: ...
    def edit_pending(self, action_id: str, arguments: dict[str, Any], action_hash: str, *, expires_at: str) -> ProposedAction | None: ...
    def approve(self, action_id: str, *, expected_hash: str, note: str = "", decided_by: str = "local-human") -> ProposedAction | None: ...
    def reject(self, action_id: str, *, note: str = "", decided_by: str = "local-human") -> ProposedAction | None: ...
    def mark_expired(self, action_id: str) -> ProposedAction | None: ...
    def claim_execution(self, action_id: str, *, expected_hash: str, execution_id: str) -> ProposedAction | None: ...
    def finalize_execution(self, action_id: str, *, execution_id: str, ok: bool, result_summary: str | None = None, error: str | None = None) -> ProposedAction | None: ...
    def recover_inflight(self) -> list[ProposedAction]: ...


@runtime_checkable
class ApprovalService(Protocol):
    def propose(self, tool: ToolDefinition, arguments: dict[str, Any], context: ToolContext) -> ProposedAction: ...
    def get(self, action_id: str) -> ProposedAction | None: ...
    def list(self, *, limit: int = 100, status: ApprovalStatus | None = None) -> list[ProposedAction]: ...
    def edit(self, action_id: str, arguments: dict[str, Any]) -> ProposedAction: ...
    def approve(self, action_id: str, *, note: str = "", decided_by: str = "local-human") -> ProposedAction: ...
    def reject(self, action_id: str, *, note: str = "", decided_by: str = "local-human") -> ProposedAction: ...


@runtime_checkable
class ActionExecutor(Protocol):
    def execute(self, action_id: str, *, observer=None) -> tuple[ProposedAction, ToolResult]: ...
